#!/usr/bin/env python3
"""Generate method_names.h from engine_*.def files.

usage: method_names_gen.py -o OUT DEF [DEF...]
"""
import argparse
import os
import re

ENGINE_RE = re.compile(r"^\s*engine\s+(\w+)\s+(0x[0-9a-fA-F]+)\s*;")
ENTRY_RE = re.compile(r"^\s*(0x[0-9a-fA-F]+)\s+(\w+)\b(.*)$")
ARRAY_RE = re.compile(r"\barray\[(\d+)\]")


def strip_comment(line):
	return line.split("//", 1)[0]


def entry_size(rest):
	return 2 if re.search(r"\biova\b", rest) else 1


def parse_def(path):
	cls = None
	entries = []
	depth = 0
	struct = None  # top-level array entry whose members are being collected
	for raw in open(path):
		line = strip_comment(raw)
		m = ENGINE_RE.match(line)
		if m:
			cls = int(m.group(2), 16)
			continue

		m = ENTRY_RE.match(line)
		if m and depth == 0:
			off, name, rest = int(m.group(1), 16), m.group(2), m.group(3)
			am = ARRAY_RE.search(rest)
			opens_struct = am is not None and rest.rstrip().endswith("(") and not re.search(r"\b(bits|enum)\b", rest)
			entry = {
				"offset": off,
				"name": name,
				"count": int(am.group(1)) if am else 1,
				"stride": entry_size(rest),
				"size": entry_size(rest),
				"members": [],
			}
			entries.append(entry)
			if opens_struct:
				struct = entry
		elif m and depth == 1 and struct is not None:
			off, name, rest = int(m.group(1), 16), m.group(2), m.group(3)
			if name == "next":
				struct["stride"] = off
				struct["size"] = off
			else:
				struct["members"].append((off, name))

		depth += line.count("(") - line.count(")")
		if depth == 0:
			struct = None

	if cls is None:
		raise SystemExit("%s: no engine declaration" % path)
	return cls, entries


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("-o", "--output", required=True)
	ap.add_argument("defs", nargs="+")
	args = ap.parse_args()

	out = []
	out.append("// Generated by method_names_gen.py from the engine .def files, do not edit.")
	out.append("#pragma once")
	out.append("#include <stdint.h>")
	out.append("")
	out.append("namespace maxwell::method_names")
	out.append("{")
	out.append("\tstruct Member { uint16_t offset; const char* name; };")
	out.append("\tstruct Entry { uint32_t cls; uint16_t offset, count, stride, size; const Member* members; uint16_t numMembers; const char* name; };")
	out.append("")

	rows = []
	for path in sorted(args.defs, key=os.path.basename):
		cls, entries = parse_def(path)
		for e in entries:
			mref, nm = "nullptr", 0
			if e["members"]:
				mname = "m_%04X_%03X" % (cls, e["offset"])
				items = ", ".join('{ 0x%02X, "%s" }' % (o, n) for o, n in e["members"])
				out.append("\tconstexpr Member %s[] = { %s };" % (mname, items))
				mref, nm = mname, len(e["members"])
			rows.append('\t\t{ 0x%04X, 0x%03X, %u, %u, %u, %s, %u, "%s" },' % (
				cls, e["offset"], e["count"], e["stride"], e["size"], mref, nm, e["name"]))

	out.append("")
	out.append("\tconstexpr Entry Table[] =")
	out.append("\t{")
	out.extend(rows)
	out.append("\t};")
	out.append("}")
	out.append("")

	with open(args.output, "w") as f:
		f.write("\n".join(out))


if __name__ == "__main__":
	main()
